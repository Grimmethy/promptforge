// Hand-offs on the page (web/handoff.js helpers, web/app.js wiring). node --test test/*.test.js
const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const { isId, specFromPayload, describe, idFromSearch, idFromMessage } = require('../web/handoff.js');

const read = (f) => fs.readFileSync(path.join(__dirname, '..', 'web', f), 'utf8');
const ID = 'a'.repeat(32);

test('isId accepts only 32 lowercase hex characters', () => {
  assert.strictEqual(isId(ID), true);
  for (const bad of ['', 'abc', 'A'.repeat(32), 'g'.repeat(32), ID + 'a', null, 5, '../' + ID]) assert.strictEqual(isId(bad), false);
});

test('specFromPayload uses the payload spec when there is one, else builds one custom character card', () => {
  const own = { characters: [{ name: 'x' }], seed: 1 };
  assert.strictEqual(specFromPayload({ spec: own, prompt: 'ignored' }), own);
  const s = specFromPayload({ kind: 'image', prompt: 'a goat', model: 'm.safetensors', seed: 7, style: 'watercolor', negative: 'bad', source: { slug: 'Hooble' } });
  assert.deepStrictEqual(s.characters, [{ source: 'custom', name: 'Hooble', expression: 'none', weight: 1, outfit: {}, colors: {}, text: 'a goat' }]);
  assert.deepStrictEqual([s.model, s.seed, s.style, s.negative, s.theme], ['m.safetensors', 7, 'watercolor', 'bad', 'none']);
  const bare = specFromPayload({ kind: 'image' });
  assert.strictEqual(bare.characters[0].name, 'character');
  assert.strictEqual(bare.characters[0].text, '');
  assert.ok(!('model' in bare) && !('seed' in bare));
  assert.ok(specFromPayload({ spec: {} }).characters, 'an empty spec object falls back to the card');
  assert.ok(specFromPayload(undefined).characters);
});

test('describe says where the hand-off came from', () => {
  assert.strictEqual(describe({ kind: 'image', source: { forge: 'characterforge', slug: 'Hooble', role: 'pose' } }), 'Loaded from characterforge: Hooble (pose)');
  assert.strictEqual(describe({ kind: 'slot', slot: { forge: 'characterforge', slug: 'Gobs', role: 'outfit' } }), 'Empty slot from characterforge: Gobs (outfit)');
  assert.strictEqual(describe({ kind: 'image' }), 'Loaded from a library forge');
});

test('idFromSearch and idFromMessage accept only a well formed id and the right message type', () => {
  assert.strictEqual(idFromSearch('?handoff=' + ID), ID);
  assert.strictEqual(idFromSearch('?handoff=zzz'), null);
  assert.strictEqual(idFromSearch('?other=' + ID), null);
  assert.strictEqual(idFromSearch(''), null);
  assert.strictEqual(idFromMessage({ type: 'pf-handoff', id: ID }), ID);
  assert.strictEqual(idFromMessage({ type: 'other', id: ID }), null);
  assert.strictEqual(idFromMessage({ type: 'pf-handoff', id: 'x' }), null);
  assert.strictEqual(idFromMessage(null), null);
});

test('app.js applies a hand-off from the URL once and from a same-host message only', () => {
  const a = read('app.js');
  assert.match(a, /history\.replaceState\(null, '', location\.pathname\); applyHandoff\(hid\);/);
  assert.match(a, /new URL\(e\.origin\)\.hostname === location\.hostname/);
  assert.match(a, /const hid = same \? PFHandoff\.idFromMessage\(e\.data\) : null;/);
  assert.match(a, /for \(let i = 0; i < 50 && !\(\$\('#model'\) && \$\('#model'\)\.options\.length\); i\+\+\)/);
});

test('an image hand-off opens the regenerate panel with the sent picture and the run uploads it', () => {
  const a = read('app.js');
  assert.match(a, /openRegen\('', \{ prompt_used: \{ positive: p\.prompt \|\| '' \}, model: p\.model \}\); _regenFile = null; _regenHandoff = hid; \$\('#regenImg'\)\.src = p\.image_url;/);
  assert.match(a, /if \(!_regenFile && !_regenHandoff\) return;/);
  assert.match(a, /if \(_regenHandoff\) fd\.append\('image', await fetch\('\/api\/handoff\/' \+ _regenHandoff \+ '\/image'\)\.then\(r => r\.blob\(\)\), 'handoff\.png'\);\s*\/\/[^\n]*\n\s*else fd\.append\('from_gallery', _regenFile\);/);
  assert.match(a, /function closeRegen\(\) \{[^}]*_regenHandoff = null; \}/);
  assert.match(a, /if \(file\) \$\('#regenImg'\)\.src = '\/api\/image\/' \+ file;/);
});

test('nothing is generated by a hand-off, and the script loads before app.js', () => {
  const a = read('app.js');
  const block = a.slice(a.indexOf('async function applyHandoff'), a.indexOf('boot();', a.indexOf('async function applyHandoff')));
  assert.doesNotMatch(block, /\/api\/generate|\/api\/regenerate|generate\(\)|runRegen/);
  const h = read('index.html');
  assert.ok(h.indexOf('/handoff.js') > 0 && h.indexOf('/handoff.js') < h.indexOf('/app.js'));
});
